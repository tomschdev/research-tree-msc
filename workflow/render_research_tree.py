#!/usr/bin/env python3
"""Render the research tree as a mermaid diagram.

Usage (from the repo root):
  python3 workflow/render_research_tree.py         # write research-tree/tree.mmd and tree.md
  python3 workflow/render_research_tree.py --svg   # also research-tree/tree.svg (mmdc, else npx mermaid-cli)
"""
import shutil
import subprocess
import sys

sys.dont_write_bytecode = True  # keep workflow/ free of __pycache__
from validate_research_tree import ROOT, load_tree  # noqa: E402

OUT = ROOT / "research-tree"
OPEN_STYLE = "fill:#f5f5f5,stroke:#999,color:#333"


def diagram(definitions, nodes):
    nodes = dict(sorted(nodes.items(), key=lambda kv: str(kv[1]["q"].get("path") or "")))
    ids = {nid: f"n{i}" for i, nid in enumerate(nodes)}
    out = ["graph TD"]
    for nid, n in nodes.items():
        c = n["c"] or {}
        conclusion = c.get("conclusion") or "open"
        detail = conclusion + (f" · {c['basis']}" if c.get("basis") else "")
        out.append(f'  {ids[nid]}["{nid}<br/><i>{detail}</i>"]:::{conclusion}')
    for nid, n in nodes.items():
        parent = nodes.get(n["parent"])
        if not parent:
            continue
        pc = parent["c"] or {}
        if pc.get("conclusion") == "bypassed" and pc.get("bypassed_by") == nid:
            out.append(f"  {ids[n['parent']]} -. bypassed by .-> {ids[nid]}")
        else:
            out.append(f"  {ids[n['parent']]} --> {ids[nid]}")
    out.append(f"  classDef open {OPEN_STYLE}")
    for name, spec in definitions.items():
        if spec.get("style"):
            out.append(f"  classDef {name} {spec['style']}")
    return "\n".join(out) + "\n"


def main(argv):
    definitions, nodes, errors = load_tree()
    if errors:
        print("tree has structural errors; run validate_research_tree.py", file=sys.stderr)
    mmd = diagram(definitions, nodes)
    (OUT / "tree.mmd").write_text(mmd)
    (OUT / "tree.md").write_text(
        "# Research tree\n\nGenerated by `workflow/render_research_tree.py` — do not edit.\n\n"
        f"```mermaid\n{mmd}```\n")
    print("wrote research-tree/tree.mmd, research-tree/tree.md")
    if "--svg" in argv:
        cmd = ["mmdc"] if shutil.which("mmdc") else ["npx", "-y", "@mermaid-js/mermaid-cli"]
        subprocess.run(cmd + ["-i", "tree.mmd", "-o", "tree.svg"], cwd=OUT, check=True)
        print("wrote research-tree/tree.svg")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
